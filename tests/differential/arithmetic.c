#include <math.h>
#include <stdio.h>
int main(void) {
    printf("%g\n", 7.0 + 2.0);
    printf("%g\n", 7.0 - 2.0);
    printf("%g\n", 7.0 * 2.0);
    printf("%g\n", 7.0 / 2.0);
    printf("%g\n", fmod(7.0, 2.0));
    printf("%g\n", fmod(-3.0, 2.0));
    printf("%g\n", pow(2.0, 10.0));
    return 0;
}
